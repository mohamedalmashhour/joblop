/** Fill {name} placeholders. */
export function fillIn(template: string, vars: Readonly<Record<string, string | number>>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

/** A status code in words, or the code with spaces when it is new. */
export function statusWord(words: Readonly<Record<string, string>>, code: string): string {
  return words[code] ?? code.replaceAll("_", " ");
}
